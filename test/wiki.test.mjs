// #188: the wiki for a product owner: a front page and one small page per capability, each with its
// contents, written again only when its inputs change; an old generated page no feature makes goes.
import fs from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import assert from "node:assert/strict";

const req = createRequire(import.meta.url);
const { openDb } = req("../vscode/db.js");
const { buildWiki, pageText, anchor, firstLine } = req("../vscode/wiki.js");
const { generatedText, inside } = req("../vscode/docs-export.js");
const header = "<!-- Generated by Imprimatur from its database; test -->";
const user = { kind: "user" };

const PAGE = "# Meeting notes in one place\n\nYour meeting notes land on the work they are about.\n\n## What it does for you\n\n- Decisions stay with the work.\n\n## How it works\n\n1. You hold a meeting.\n\n## Words used here\n\n- task: a piece of work.";
const INTRO = "Imprimatur keeps what your coding assistant does in view.\n\n## Who it is for\n\n- People who work with an AI assistant.";

test("pageText: title, lead, a contents list linking each section, a way back", () => {
  const t = pageText(header, PAGE, "meetings");
  assert.match(t, /^<!-- Generated[^\n]*\n\n# Meeting notes in one place\n\nYour meeting notes land/);
  assert.match(t, /## Contents\n\n- \[What it does for you\]\(#what-it-does-for-you\)\n- \[How it works\]\(#how-it-works\)\n- \[Words used here\]\(#words-used-here\)/);
  assert.match(t, /\[Back to the wiki\]\(README\.md\)\n$/);
  assert.equal(anchor("Good to know"), "good-to-know");
  assert.equal(firstLine("# T\n\nFirst one. Second one."), "First one.");
  assert.match(firstLine(`# T\n\n${"word ".repeat(50)}`), /word…$/);
});

test("wiki: a page per capability and the front page listing them; not asked again while the inputs stay; old module pages go", async () => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "imprimatur-188-")));
  const db = openDb({ path: path.join(root, "x.db") });
  const repo = db.repoOf(root);
  db.upsertSection(db.docOf(repo.id, "project").id, "overview", { title: "Overview", body: "Imprimatur keeps an agent's work in front of the user.", chapter: "mission" }, user);
  const cap = db.taskDocOf(repo.id, "meetings", "capability");
  db.upsertSection(cap.id, "records", { title: "A meeting's note", body: "A meeting app writes its notes as a `meeting` record on the task (#167)." }, user);
  fs.mkdirSync(path.join(root, "docs", "wiki"), { recursive: true });
  fs.writeFileSync(path.join(root, "docs", "wiki", "hooks.md"), `${header}\n\n# hooks/\n`);
  fs.writeFileSync(path.join(root, "docs", "wiki", "notes.md"), "# My own page\n");
  const asked = [];
  const ask = async (p) => (asked.push(p), p.includes('"meetings" feature') ? PAGE : INTRO);
  const io = { header, generatedText, inside: (f) => inside(root, f), ask };
  await buildWiki(db, repo, root, io);
  assert.equal(asked.length, 2, "the meetings page and the intro");
  assert.match(asked[0], /product owner/);
  assert.match(asked[0], /meeting app writes its notes/);
  const wiki = (f) => fs.readFileSync(path.join(root, "docs/wiki", f), "utf8");
  assert.match(wiki("meetings.md"), /# Meeting notes in one place/);
  assert.match(wiki("README.md"), /Imprimatur keeps what your coding assistant does in view\./);
  assert.match(wiki("README.md"), /## Pages\n\n- \[Meeting notes in one place\]\(meetings\.md\): Your meeting notes land on the work they are about\./);
  assert.match(wiki("README.md"), /## Contents\n\n- \[Who it is for\]\(#who-it-is-for\)\n- \[Pages\]\(#pages\)\n\n## Who it is for/);
  assert.equal(fs.existsSync(path.join(root, "docs/wiki/hooks.md")), false, "an old generated module page goes");
  assert.equal(wiki("notes.md"), "# My own page\n", "a hand-written page stays");
  const front = wiki("README.md");
  await buildWiki(db, repo, root, io);
  assert.equal(asked.length, 2, "inputs unchanged: not asked again");
  assert.equal(wiki("README.md"), front, "the front page stays the same");
  db.upsertSection(cap.id, "transcript", { title: "Transcript", body: "The raw transcript sits beside the note." }, user);
  await buildWiki(db, repo, root, io);
  assert.equal(asked.length, 3, "the capability changed: its page is written again, the intro is not");
  assert.match(wiki("README.md"), /Imprimatur keeps what your coding assistant does in view\./, "the intro is kept");
});
