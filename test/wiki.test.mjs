// #188: the generated wiki: one page per code module from its files' comments and ADRs, written again only when they change.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import assert from "node:assert/strict";

const req = createRequire(import.meta.url);
const { openDb } = req("../vscode/db.js");
const { buildWiki, headerOf } = req("../vscode/wiki.js");
const { generatedText, inside } = req("../vscode/docs-export.js");
const header = "<!-- Generated by Imprimatur from its database; test -->";

test("wiki: a page per module from comments and ADRs, the index, nothing asked again while the inputs stay", async () => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "imprimatur-188-")));
  execFileSync("git", ["init", "-q", root]);
  fs.mkdirSync(path.join(root, "src"));
  fs.writeFileSync(path.join(root, "src", "store.js"), "// The store: one SQLite file per device.\nconst x = 1;\n");
  fs.mkdirSync(path.join(root, "test"));
  fs.writeFileSync(path.join(root, "test", "a.test.js"), "// a test\n");
  execFileSync("git", ["-C", root, "add", "."]);
  assert.equal(headerOf(path.join(root, "src", "store.js")), "The store: one SQLite file per device.");
  const db = openDb({ path: path.join(root, "x.db") });
  const repo = db.repoOf(root);
  const t = db.upsertTask(repo.id, "#1", { title: "T" });
  db.addRecord(t.id, { kind: "adr", title: "SQLite is the source of truth", links: { files: ["src/store.js"] } }, { kind: "agent", id: "s" });
  const asked = [];
  const ask = async (p) => (asked.push(p), "The src module stores records.\n\n```mermaid\nflowchart LR\n  a --> b\n```\n\n## Parts\n\n- `src/store.js`: the store");
  const io = { header, generatedText, inside: (f) => inside(root, f), ask };
  await buildWiki(db, repo, root, io);
  assert.equal(asked.length, 1, "one module: src (test/ is skipped)");
  assert.match(asked[0], /one SQLite file per device/);
  assert.match(asked[0], /SQLite is the source of truth/);
  assert.match(fs.readFileSync(path.join(root, "docs/wiki/src.md"), "utf8"), /# src\/\n\nThe src module stores records\./);
  assert.match(fs.readFileSync(path.join(root, "docs/wiki/README.md"), "utf8"), /- \[src\/\]\(src\.md\): The src module stores records\./);
  await buildWiki(db, repo, root, io);
  assert.equal(asked.length, 1, "inputs unchanged: not asked again");
  db.addRecord(t.id, { kind: "adr", title: "WAL is bounded", links: { files: ["src/store.js"] } }, { kind: "agent", id: "s" });
  await buildWiki(db, repo, root, io);
  assert.equal(asked.length, 2, "a new ADR about the module: written again");
});
