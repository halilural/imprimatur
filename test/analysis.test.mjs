function gitRepo() {
  const root = tmpDir();
  execFileSync("git", ["init", "-q", "-b", "main"], { cwd: root });
  return root;
}
/** A database with a repo and tasks #5 and LATD-12. */
function seeded(root = "/a/proj", origin) {
  const db = openDb({ path: tmpDb() });
  const repo = db.repoOf(root, origin ? { origin } : {});
  for (const k of ["#5", "LATD-12", "#80"]) db.upsertTask(repo.id, k, { title: `task ${k}` });
  return { db, repo };
}

