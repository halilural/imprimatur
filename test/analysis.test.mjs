test("review fixes: long headings alike stay two sections; an older replayed state sets nothing back; one model call per file at a time", () => {
  const { db, repo } = seeded();
  const long = "Risks of migrating the database schema from the old layout";
  const r = a.ingest(db, repo.id, "#5", "n/a-very-long-analysis-file-name.md", `# T\n\n## ${long} (prod)\n\na\n\n## ${long} (staging)\n\nb\n\n## Same\n\nx\n\n## Same\n\ny\n`, { actor: hook });
  const secs = db.docSections(db.taskDocFind(repo.id, "#5").id);
  assert.equal(r.changed, 4);
  assert.equal(new Set(secs.map((s) => s.key)).size, 4);
  for (const s of secs) assert.ok(s.key.length <= 64, s.key);
  // Newer text already in (the hook, a peer, MCP): an older state from the past is skipped.
  a.ingest(db, repo.id, "#80", "n/x.md", "# X\n\n## A\n\nnew\n", { actor: hook, at: 2_000 });
  const old = a.ingest(db, repo.id, "#80", "n/x.md", "# X\n\n## A\n\nold\n", { actor: hook, at: 1_000 });
  assert.equal(old.unchanged, true);
  assert.equal(db.docSections(db.taskDocFind(repo.id, "#80").id)[0].body, "new");
  // The model's file: started once, not again while it is pending.
  const root = gitRepo();
  const s2 = seeded(root);
  const started = [];
  const it = { rel: "notes.md", text: "# Kurulum\n", actor: hook };
  a.onEdit(s2.db, s2.repo.id, root, it, { start: () => started.push(1) });
  a.onEdit(s2.db, s2.repo.id, root, it, { start: () => started.push(1) });
  assert.equal(started.length, 1);
  assert.equal(a.onEdit(s2.db, s2.repo.id, root, { ...it, text: "x".repeat(1_000_001) }, { start: () => started.push(1) }).status, "later");
  assert.equal(started.length, 1);
});

test("taskFor: every folder of the path, nearest first; a number prefix only when it is a task", () => {
  const db = openDb({ path: tmpDb() });
  const repo = db.repoOf("/a/other");
  db.upsertTask(repo.id, "LATD-9999", {});
  db.upsertTask(repo.id, "LATD-traceability", {});
  const t = (rel) => a.taskFor(db, repo.id, { rel, text: "" });
  // "01-initpayload" is not #1 (no such task): the ticket folder above it is.
  assert.equal(t("docs/analysis/LATD-9999/01-initpayload/analysis.md"), "LATD-9999");
  assert.equal(t("docs/analysis/LATD-traceability/analysis.md"), "LATD-traceability");
  for (const dir of ["drafts", "mails", "attachments", "walkthroughs", "reviews"]) assert.equal(t(`docs/${dir}/LATD-9999/notes.md`), "LATD-9999");
  // With #1 a task, the nearer folder wins.
  db.upsertTask(repo.id, "#1", {});
  assert.equal(t("docs/analysis/LATD-9999/01-initpayload/analysis.md"), "#1");
  assert.equal(t("docs/analysis/unknown/x.md"), undefined);
});

