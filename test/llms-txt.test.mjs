// llms.txt at the repo root (#216): Imprimatur's documents listed for other agents.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { test } from "node:test";
import assert from "node:assert/strict";

const { writeLlms } = createRequire(import.meta.url)("../vscode/llms-txt.js");
const HEADER = "<!-- Generated by Imprimatur from its database; test -->";
const io = (root) => ({ header: HEADER, generatedText: (t) => t.startsWith("<!-- Generated by Imprimatur"), inside: (f) => f.startsWith(root) });

test("llms.txt: lists the documents present with a title and a description; follows a removal; leaves a hand-written one", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "imprimatur-216-"));
  const put = (f, t) => {
    fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true });
    fs.writeFileSync(path.join(root, f), t);
  };
  put("docs/PROJECT.md", `${HEADER}\n\n# Project\n\n<a id="chapter-mission"></a>\n\nA tool that keeps agents honest.\n`);
  put("docs/adr/0001-one.md", "---\nstatus: accepted\n---\n\n# One choice\n\nWe chose one.\n");
  put("docs/adr/0002-two.md", "# Two choice\n\nWe chose two.\n");
  put("GLOSSARY.md", "# Terms\n\nThe words.\n");
  assert.equal(writeLlms(root, "demo", io(root)), true);
  const text = fs.readFileSync(path.join(root, "llms.txt"), "utf8");
  assert.match(text, /^<!-- Generated by Imprimatur[\s\S]*# demo\n\n> A tool that keeps agents honest\.\n/);
  assert.match(text, /## Decisions\n\n- \[One choice\]\(docs\/adr\/0001-one\.md\): We chose one\.\n- \[Two choice\]\(docs\/adr\/0002-two\.md\): We chose two\./);
  assert.match(text, /## Terms\n\n- \[Terms\]\(GLOSSARY\.md\): The words\./);
  assert.equal(writeLlms(root, "demo", io(root)), false, "unchanged: not written again");
  fs.rmSync(path.join(root, "docs/adr/0002-two.md"));
  writeLlms(root, "demo", io(root));
  assert.doesNotMatch(fs.readFileSync(path.join(root, "llms.txt"), "utf8"), /0002-two/);
  fs.writeFileSync(path.join(root, "llms.txt"), "# mine\n");
  assert.equal(writeLlms(root, "demo", io(root)), false);
  assert.equal(fs.readFileSync(path.join(root, "llms.txt"), "utf8"), "# mine\n");
});

test("llms.txt: a symbolic link among the documents is not followed, so no outside file's text is copied", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "imprimatur-216l-"));
  const secret = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "outside-")), "secret.md");
  fs.writeFileSync(secret, "# Secret\n\nTOKEN=abc123\n");
  fs.mkdirSync(path.join(root, "docs/adr"), { recursive: true });
  fs.writeFileSync(path.join(root, "docs/adr/0001-one.md"), "# One\n\nWe chose one.\n");
  fs.symlinkSync(secret, path.join(root, "docs/adr/0002-link.md"));
  fs.symlinkSync(secret, path.join(root, "GLOSSARY.md"));
  writeLlms(root, "demo", io(root));
  const text = fs.readFileSync(path.join(root, "llms.txt"), "utf8");
  assert.match(text, /0001-one/);
  assert.doesNotMatch(text, /TOKEN|Secret|0002-link|GLOSSARY/);
});
