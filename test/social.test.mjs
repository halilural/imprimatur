// Social media as a living document (#109): off by default per repo, turned on in
// .claude/imprimatur.json; then a Social document in the panel, docs/SOCIAL.md and the MCP tools.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import Module, { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import assert from "node:assert/strict";
import { callTool } from "../mcp/server.mjs";

const req = createRequire(import.meta.url);
const { openDb } = req("../vscode/db.js");
const { socialOn, setSocial, kindsOf, exportDocs, fileOf } = req("../vscode/docs-export.js");
const load = Module._load;
Module._load = function (r, ...a) {
  return r === "vscode" ? {} : load.call(this, r, ...a);
};
const tasksView = req("../vscode/tasksView.js");
Module._load = load;

const repoDir = () => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "imprimatur-109-")));
  execFileSync("git", ["init", "-q", root]);
  return root;
};
const settings = (root) => JSON.parse(fs.readFileSync(path.join(root, ".claude", "imprimatur.json"), "utf8"));

test("off by default; turned on and off in .claude/imprimatur.json, other settings kept", () => {
  const root = repoDir();
  assert.equal(socialOn(root), false);
  assert.deepEqual(kindsOf(root), ["architecture", "product", "glossary"]);
  fs.mkdirSync(path.join(root, ".claude"));
  fs.writeFileSync(path.join(root, ".claude", "imprimatur.json"), JSON.stringify({ lang: "English", docs: { dir: "docs" } }));
  setSocial(root, true);
  assert.deepEqual(settings(root), { lang: "English", docs: { dir: "docs" }, social: true });
  assert.ok(socialOn(root));
  assert.deepEqual(kindsOf(root), ["architecture", "product", "glossary", "social"]);
  setSocial(root, false);
  assert.deepEqual(settings(root), { lang: "English", docs: { dir: "docs" } });
  fs.writeFileSync(path.join(root, ".claude", "imprimatur.json"), "{ not json");
  assert.throws(() => setSocial(root, true), /not valid JSON/);
  assert.equal(fs.readFileSync(path.join(root, ".claude", "imprimatur.json"), "utf8"), "{ not json", "a broken file is left as it was");
});

test("MCP: the social document is refused while off; on, sections are written and docs/SOCIAL.md follows", () => {
  const root = repoDir();
  const db = openDb({ path: path.join(root, "i.db") });
  assert.throws(() => callTool(db, "doc_get", { kind: "social", repo: root }), /social media tracking is off/);
  assert.throws(() => callTool(db, "doc_section_upsert", { kind: "social", key: "x", title: "X", repo: root }), /off by default/);

  setSocial(root, true);
  const out = callTool(db, "doc_section_upsert", { kind: "social", key: "reddit-claudecode", title: "Reddit r/ClaudeCode", body: "Rules read 2026-10-24: ...\n\nThe post.", repo: root });
  assert.equal(out.created, true);
  assert.equal(out.document.title, "Social Media");
  assert.equal(out.file.path, path.join("docs", "SOCIAL.md"));
  const md = fs.readFileSync(fileOf(root, "social"), "utf8");
  assert.match(md, /^<!-- Generated by Imprimatur[\s\S]*# Social Media[\s\S]*## 1\. Reddit r\/ClaudeCode[\s\S]*The post\./);
  assert.equal(callTool(db, "doc_get", { kind: "social", repo: root, full: true }).sections[0].key, "reddit-claudecode");

  // Off again: the document stays in the database and its file is left as it is, not written.
  setSocial(root, false);
  assert.throws(() => callTool(db, "doc_get", { kind: "social", repo: root }), /off/);
  db.upsertSection(db.docFind(db.repoByRoot(root).id, "social").id, "reddit-claudecode", { body: "changed while off" }, { kind: "user" });
  assert.ok(!exportDocs(db, root).some((r) => r.kind === "social"), "not exported while off");
  assert.equal(fs.readFileSync(fileOf(root, "social"), "utf8"), md);
});

test("panel: Social shows under Analysis only where it is on; off, its page says how to turn it on", () => {
  const root = repoDir();
  const db = openDb({ path: path.join(root, "i.db") });
  db.repoOf(root);
  const off = tasksView.paneHtml(db, root, { tab: "architecture" });
  assert.ok(!off.includes('data-tab="social"'));
  assert.match(tasksView.paneHtml(db, root, { tab: "social" }), /Social media tracking is off in this repo/);
  setSocial(root, true);
  const on = tasksView.paneHtml(db, root, { tab: "social" });
  assert.match(on, /data-tab="social"[^>]*aria-current="page"/);
  assert.match(on, /No posts yet[\s\S]*\/social-post/);
  assert.throws(() => tasksView.applyMessage(db, { type: "docNew", kind: "social", title: "X" }, { kind: "user" }, repoDir()), /off in this repo/);
  tasksView.applyMessage(db, { type: "docNew", kind: "social", title: "Show HN", body: "Write it by hand." }, { kind: "user" }, root);
  assert.match(tasksView.paneHtml(db, root, { tab: "social" }), /Show HN/);
  assert.deepEqual(tasksView.cleanView({ tab: "social" }), { tab: "social" });
});
