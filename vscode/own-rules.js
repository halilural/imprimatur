// Imprimatur's own rules in a file of their own (#208): .claude/rules/imprimatur.md, generated and
// rewritten at each session start, so a release's rule change reaches every repo and never mixes
// with the repo's own rules (AGENTS.md, its other rules files) or a third party's. A file the user
// took over (its header removed) is left alone. Cursor's imported rules and rulesync do the same.
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const FILE = path.join(".claude", "rules", "imprimatur.md");
const HEADER = "<!-- Generated by Imprimatur: it rewrites this file at each session start. Put your own rules in AGENTS.md or another rules file. -->";
const HEADER_START = "<!-- Generated by Imprimatur";

const TEXT = `${HEADER}

# Imprimatur

Imprimatur's rules for this repo, loaded in every session. The repo's own rules are in AGENTS.md and the other rules files; where they disagree, the repo's own rules win.

## Tasks and records

- Tasks and records live in Imprimatur (its MCP server): start with \`where_we_left_off\`, keep a task's summary a one-line "where we are", and write decisions as records.

## Documents

- \`docs/PROJECT.md\`, \`docs/capabilities/\`, \`docs/adr/\`, \`GLOSSARY.md\` and \`.out-of-scope/\` are generated from Imprimatur's database (Matt Pocock's model): change them with \`doc_section_upsert\`, an ADR with \`record_add\`/\`record_update\`, or in the Imprimatur panel, not by hand. The next export writes over a hand edit, except an ADR file, which is read back into its record.
- A task's spec comes before its code and goes through Matt Pocock's \`to-spec\` gates: stories, design, analyze, then tickets. \`/to-spec\`, \`/to-tickets\` and \`/wayfinder\` are started by the user; when you start a task yourself, read the to-spec skill's SKILL.md and write the spec the same way with \`doc_section_upsert\` (kind \`spec\`). Work too big for one session starts with \`/wayfinder\`. A product choice lives in the spec.
- An ADR (record kind \`adr\`) is only for a decision that is hard to reverse, surprising without its context, and the result of a real trade-off; it stands alone.
- A spec section that changes a capability carries its delta (added, modified, removed, renamed), keyed \`<capability>--<requirement>\`; it merges into the capability when the task is done.
- A new term, or a term that changes meaning, goes in the glossary, one section per term.
- Diagrams are Mermaid. Draw the C4 levels as flowcharts with \`[Person]\`, \`[Software system]\` and \`[Container: technology]\` labels. Every \`sequenceDiagram\` gets \`autonumber\` and, right under it, a numbered list explaining each arrow.
- Hand-written documents the repo keeps (\`docs.keep\` in \`.claude/imprimatur.json\`) stay files: \`search\` finds inside them; read one only when you need it.

## Asking the user

- When the user approves (a list, "do all", "go on", "yes", "hepsini yap", "devam"), do every item it covers in that turn, the commits, pushes and deletions it names included; do not list them again as questions.
- Ask only for a decision that is new and the user's: a real choice you cannot settle from the code, the records or their earlier answers. Put such questions in one line, once. Something only the user can do is said once, not in every reply.

## Evidence before claims

- Never state that something passes, works, is fixed, done or true without evidence from this turn: name the command that proves it, run it, read its whole output and exit code, then state the result with that evidence. A previous run, "should work", a linter for a build, or tests for a requirement are not evidence.
- An agent's or another session's "success" is a claim too: check the diff or the output yourself before repeating it.
- What you did not measure, say so ("not verified"); do not guess. For a bug, build a loop that goes red on it before theorising (the \`diagnosing-bugs\` skill); before saying work is done, follow \`verification-before-completion\`.
`;

/** Whether a text is Imprimatur's generated rules file. @param {string | undefined} text */
const generated = (text) => String(text ?? "").startsWith(HEADER_START);

/**
 * Writes the repo's .claude/rules/imprimatur.md when it is missing or Imprimatur's own and out of
 * date. A hand-taken file (no header) or a link on the way is left alone.
 * @param {string} root @returns {"written" | "same" | "hand" | "unsafe"}
 */
function writeOwnRules(root) {
  const file = path.join(root, FILE);
  const { safeTarget } = require("./agent-files.js");
  if (!safeTarget(root, file)) return "unsafe";
  let old;
  try {
    old = fs.readFileSync(file, "utf8");
  } catch {}
  if (old === TEXT) return "same";
  if (old !== undefined && !generated(old)) return "hand";
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!safeTarget(root, file)) return "unsafe";
  fs.writeFileSync(file, TEXT);
  return "written";
}

/**
 * Imprimatur's rules copied into the repo's own files by older releases (#208): lines only
 * Imprimatur's templates wrote. @param {string} text @returns {string[]} the copied lines found
 */
function copiedLines(text) {
  return String(text ?? "").split("\n").filter((l) => OLD_LINES.some((re) => re.test(l)));
}
const OLD_LINES = [
  /tasks and records live in Imprimatur \(its MCP server\)/,
  /are generated by Imprimatur \(Matt Pocock's model\)/,
  /^- Imprimatur's database is the source of these files/,
  /^- A task's spec (?:is written with `\/to-spec`|goes through Matt Pocock's `to-spec` gates)/,
];

module.exports = { FILE, HEADER, TEXT, generated, writeOwnRules, copiedLines };
