// @ts-check
// The repo's wiki for a product owner (#188, rewritten): small pages in plain words, generated, never
// edited by hand. docs/wiki/README.md says what the product is and lists the pages; docs/wiki/<feature>.md
// is one page per capability (how a feature behaves now). Each page is short and opens with its own
// contents list; many small pages, never one big one. The model (the user's Claude, `claude -p`) writes
// them from what the database already says: the project's mission, each capability, the glossary terms
// they use. A page is written again only when what it is made from, or the prompt, changed (a hash in meta).
"use strict";
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const DIR = path.join("docs", "wiki");
const HEADER = "<!-- Generated by Imprimatur from its database; the wiki is written again from the project page, the capabilities and the glossary: edit those. -->";
const hash = (/** @type {string} */ s) => crypto.createHash("sha1").update(s).digest("hex").slice(0, 16);
/** How much of a capability the model reads; a page stays short anyway. */
const MAX_INPUT = 8000;

/** The writing rules every page follows (part of the cache key: changing them writes the pages again). */
const VOICE = [
  "The reader is a product owner: not technical, busy, reads this to understand what the product does for people.",
  "Plain English, short sentences, everyday words. Talk to the reader as \"you\".",
  "No file names, paths, code, commands, settings, issue numbers (#123), version numbers or ADR numbers.",
  "Avoid technical words. When one cannot be avoided (agent, repo, task), say what it means in a few plain words the first time.",
  "Write like a person explaining to a colleague: no hype, no \"not X but Y\", no dashes as punctuation, no bold labels at the start of bullets, no closing summary line.",
  "Use only what is given below; do not invent features, numbers or plans. Leave out what is only about how it is built.",
];

/** The pages' inputs: the intro from the project's mission, one page per capability. @param {any} db @param {any} repo */
function pagesOf(db, repo) {
  const current = (/** @type {any} */ doc) => (doc ? db.docSections(doc.id).filter((/** @type {any} */ s) => s.status === "current") : []);
  const text = (/** @type {any[]} */ sections) => sections.map((s) => `## ${s.title}\n${String(s.body ?? "").trim()}`).join("\n\n").slice(0, MAX_INPUT);
  const glossary = current(db.docFind(repo.id, "glossary"));
  const termsIn = (/** @type {string} */ t) => glossary.filter((g) => t.toLowerCase().includes(String(g.title).toLowerCase())).slice(0, 8)
    .map((g) => ({ term: g.title, meaning: String(g.body ?? "").replace(/\s+/g, " ").slice(0, 300) }));
  const mission = current(db.docFind(repo.id, "project")).filter((s) => s.chapter === "mission" || s.key === "limits");
  const caps = db.q("SELECT * FROM documents WHERE repo_id = ? AND kind = 'capability' ORDER BY scope").all(repo.id)
    .map((/** @type {any} */ d) => ({ name: String(d.scope), source: text(current(d)) }))
    // The name becomes a file name: only a plain slug, so a synced or imported name cannot write outside docs/wiki.
    .filter((/** @type {any} */ c) => c.source.trim() && /^[a-z0-9][a-z0-9-]*$/.test(c.name));
  return {
    intro: { source: text(mission), terms: termsIn(text(mission)) },
    features: caps.map((/** @type {any} */ c) => ({ ...c, terms: termsIn(c.source) })),
  };
}

/** The prompt for one feature's page. @param {string} product @param {{name: string, source: string, terms: any[]}} f */
function featurePrompt(product, f) {
  return [
    `Write one short wiki page about the "${f.name}" feature of ${product}.`,
    ...VOICE,
    "At most 300 words. Markdown, in this order, nothing else:",
    "1. `# ` and a plain title for the feature: at most six words, sentence case (only the first word capitalised), a statement and not a question, not its internal name.",
    "2. One paragraph of two or three sentences: what this gives the reader. Its first sentence stands alone as a summary of at most 20 words.",
    "3. `## What it does for you`: three to five bullets.",
    "4. `## How it works`: numbered steps as a person using it sees them, at most six.",
    "5. `## Good to know`: up to four bullets on limits or things to keep in mind. Leave it out when there are none.",
    "6. `## Words used here`: each given term the page uses, as `- term: its meaning in one plain sentence`. Leave it out when none.",
    "",
    JSON.stringify({ feature: f.name, description: f.source, terms: f.terms }),
  ].join("\n");
}

/** The prompt for the front page's introduction. @param {string} product @param {{source: string, terms: any[]}} intro */
function introPrompt(product, intro) {
  return [
    `Write the opening of the wiki of ${product}: what it is and who it helps.`,
    ...VOICE,
    "At most 150 words. Markdown, in this order, nothing else:",
    "1. One paragraph of two or three sentences: what the product is and the problem it solves.",
    "2. `## Who it is for`: two to four bullets.",
    "",
    JSON.stringify({ product, description: intro.source, terms: intro.terms }),
  ].join("\n");
}

/** A GitHub-style heading anchor (what GitHub and VS Code's preview make of a plain heading). @param {string} h */
const anchor = (h) => h.toLowerCase().replace(/[^\p{L}\p{N} -]/gu, "").trim().replace(/ /g, "-");

/**
 * A page made from the model's answer: the title, the first paragraph, a contents list of its sections,
 * the sections, a way back. @param {string} header @param {string} answer @param {string} fallbackTitle
 * @param {boolean} [index] the front page (no way back)
 */
function pageText(header, answer, fallbackTitle, index = false) {
  let body = String(answer).trim().replace(/^```(?:markdown)?\n([\s\S]*)\n```$/, "$1").replace(/\r\n/g, "\n");
  const h1 = /^#\s+([^\n]+)\n+/.exec(body);
  const title = h1 ? h1[1].trim() : fallbackTitle;
  if (h1) body = body.slice(h1[0].length);
  body = require("./md-tidy.js").nest(body, 2);
  const heads = [...body.matchAll(/^## (.+)$/gm)].map((m) => m[1].trim());
  const at = body.search(/^## /m);
  const lead = (at < 0 ? body : body.slice(0, at)).trim();
  const rest = at < 0 ? "" : body.slice(at).trim();
  const contents = heads.length > 1 ? ["## Contents", heads.map((h) => `- [${h}](#${anchor(h)})`).join("\n")].join("\n\n") : "";
  return require("./md-tidy.js").tidy([header, `# ${title}`, lead, contents, rest, index ? "" : "[Back to the wiki](README.md)"].filter(Boolean).join("\n\n")) + "\n";
}

/** The front page: the introduction, then every page with what it is about. @param {string} intro @param {Array<{file: string, title: string, first: string}>} pages */
function indexText(intro, pages) {
  const list = ["## Pages", pages.length ? pages.map((p) => `- [${p.title}](${p.file}): ${p.first}`).join("\n") : "_No pages yet._"].join("\n\n");
  // The opening without a contents list of its own: the front page's lists every section, Pages included.
  const body = intro.replace(/\n## Contents\n[\s\S]*?(?=\n## |$)/, "\n").trimEnd() + "\n\n" + list;
  const heads = [...body.matchAll(/^## (.+)$/gm)].map((m) => m[1].trim());
  const contents = ["## Contents", heads.map((h) => `- [${h}](#${anchor(h)})`).join("\n")].join("\n\n");
  const at = body.search(/^## /m);
  return `${body.slice(0, at).trimEnd()}\n\n${contents}\n\n${body.slice(at)}\n`;
}

/**
 * Writes the wiki: each page when its inputs changed (or `force`), the front page, and takes away a
 * generated page whose feature is gone.
 * @param {any} db @param {any} repo @param {string} root
 * @param {{header: string, generatedText: (t: string) => boolean, inside: (f: string) => boolean, ask?: (prompt: string) => Promise<string>, force?: boolean, log?: (s: string) => void}} io
 * @returns {Promise<string[]>} the pages written or removed
 */
async function buildWiki(db, repo, root, io) {
  const ask = io.ask ?? ((/** @type {string} */ p) => require("./model.js").askModel(p, "sonnet", 180_000));
  const dir = path.join(root, DIR);
  if (!io.inside(path.join(dir, "README.md"))) return [];
  fs.mkdirSync(dir, { recursive: true });
  const name = String(repo.name ?? path.basename(root));
  const product = name.charAt(0).toUpperCase() + name.slice(1);
  const read = (/** @type {string} */ f) => {
    try {
      return fs.readFileSync(f, "utf8");
    } catch {
      return undefined;
    }
  };
  const written = [];
  /**
   * One page: written again when its prompt changed; a hand-written file is left alone.
   * @param {string} file @param {string} prompt @param {string} fallbackTitle @param {boolean} index
   * @returns {Promise<string | undefined>} the page's text
   */
  const page = async (file, prompt, fallbackTitle, index) => {
    const f = path.join(dir, file);
    const old = read(f);
    if (old !== undefined && !io.generatedText(old)) return old;
    const sig = hash(prompt);
    const key = `wiki:${repo.id}:${file}`;
    if (!io.force && old !== undefined && db.meta(key) === sig) return old;
    io.log?.(`${file} …`);
    let text;
    try {
      text = pageText(io.header, await ask(prompt), fallbackTitle, index);
    } catch (e) {
      io.log?.(`${file}: the model did not answer (${/** @type {Error} */ (e).message})`);
      return old;
    }
    if (!io.inside(f)) return old;
    if (!index) {
      fs.writeFileSync(f, text);
      written.push(f);
    }
    db.setMeta(key, sig);
    return text;
  };
  const { intro, features } = pagesOf(db, repo);
  const pages = [];
  for (const f of features) {
    const file = `${f.name}.md`;
    const text = await page(file, featurePrompt(product, f), f.name.replace(/-/g, " "), false);
    if (text !== undefined) pages.push({ file, title: titleOf(text) ?? f.name, first: firstLine(text) });
  }
  // A generated page no feature makes any more (the old per-module pages too) goes.
  const keep = new Set(["README.md", ...pages.map((p) => p.file)]);
  for (const name of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
    const f = path.join(dir, name);
    const t = name.endsWith(".md") && !keep.has(name) ? read(f) : undefined;
    if (t !== undefined && io.generatedText(t) && io.inside(f)) {
      fs.unlinkSync(f);
      written.push(f);
    }
  }
  const index = path.join(dir, "README.md");
  const cur = read(index);
  if (cur !== undefined && !io.generatedText(cur)) return written;
  const head = intro.source.trim() ? await page("README.md", introPrompt(product, intro), `${product}, in plain words`, true) : undefined;
  // The intro the model wrote last time, kept when it is not asked again (the page list still changes).
  const opening = head !== undefined && head !== cur ? head : cur !== undefined ? cur.split(/\n## Pages\n/)[0] : pageText(io.header, "", `${product}, in plain words`, true);
  const want = indexText(opening, pages);
  if (cur !== want) {
    fs.writeFileSync(index, want);
    written.push(index);
  }
  return written;
}

/** A page's title (its first `# ` heading). @param {string} text */
const titleOf = (text) => /^# (.+)$/m.exec(text)?.[1].trim();

/** A page's first paragraph as one line of at most 160 characters. @param {string} text */
function firstLine(text) {
  const para = String(text).split(/\n\s*\n/).find((p) => p.trim() && !/^(<!--|#|---|```|-|\[)/.test(p.trim())) ?? "";
  const one = para.replace(/\s+/g, " ").trim();
  const sentence = /^.*?[.!?](?=\s|$)/.exec(one)?.[0] ?? one;
  return sentence.length <= 160 ? sentence : `${sentence.slice(0, 160).replace(/\s+\S*$/, "")}…`;
}

module.exports = { buildWiki, pagesOf, featurePrompt, introPrompt, pageText, indexText, firstLine, anchor, DIR, HEADER };
