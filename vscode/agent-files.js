// @ts-check
// AGENTS.md as the canonical agent file (#133, decision 9331): the rules every coding agent
// follows live in AGENTS.md (at most 200 lines), CLAUDE.md imports it with `@AGENTS.md` and keeps
// only what is Claude Code's own, and the document-writing rules sit in .claude/rules/docs.md,
// scoped to docs/**. A repo with neither file gets both from the templates; one whose CLAUDE.md
// does not import AGENTS.md gets a Fix it (Claude proposes the split, the user applies the diff).
// Nothing here overwrites a file.
"use strict";
const fs = require("node:fs");
const path = require("node:path");

/** @param {string} f */
const read = (f) => {
  try {
    return fs.readFileSync(f, "utf8");
  } catch {
    return undefined;
  }
};

/** Whether a CLAUDE.md imports AGENTS.md: a line that is `@AGENTS.md` (or `@./AGENTS.md`). @param {string | undefined} text */
const importsAgents = (text) => /^\s*@(?:\.\/)?AGENTS\.md\s*$/m.test(text ?? "");

/** The agent files of a repo and how they stand. @param {string} root */
function agentFiles(root) {
  const claudeFile = path.join(root, "CLAUDE.md"), agentsFile = path.join(root, "AGENTS.md"), docsRule = path.join(root, ".claude", "rules", "docs.md");
  const claude = read(claudeFile);
  const agents = read(agentsFile);
  return {
    claudeFile, agentsFile, docsRule, claude: claude !== undefined, agents: agents !== undefined,
    imports: importsAgents(claude), docsRuleThere: fs.existsSync(docsRule),
    claudeLines: claude?.split("\n").length ?? 0, agentsLines: agents?.split("\n").length ?? 0,
  };
}

const AGENTS_TEMPLATE = `# AGENTS.md

The rules every coding agent follows in this repo. Claude Code reads them through CLAUDE.md, which imports this file; what only Claude Code needs stays there.

## Work

- Read the task and the code it touches before changing anything; change what the task needs and no more.
- Run the tests before calling a change done, and say so when they could not run.
- Ask before anything hard to undo: deleting, rewriting history, pushing, publishing.

## Tasks and records

- This repo's tasks and records live in Imprimatur (its MCP server): start with \`where_we_left_off\`, keep the task's summary a one-line "where we are", and write decisions as records.

## Documents

- \`docs/ARCHITECTURE.md\`, \`docs/PRODUCT.md\`, \`docs/GLOSSARY.md\` and \`docs/decisions/\` are generated by Imprimatur: change them through it, not by hand. The rules are in \`.claude/rules/docs.md\`.
`;

const CLAUDE_TEMPLATE = `@AGENTS.md
`;

const DOCS_RULE = `---
paths:
  - "docs/**"
---

# Writing this repo's documents

- \`docs/ARCHITECTURE.md\`, \`docs/PRODUCT.md\`, \`docs/GLOSSARY.md\` and \`docs/decisions/\` are generated from Imprimatur's database. Change them with \`doc_section_upsert\` (or in the Imprimatur panel), never in the file: the next export writes over a hand edit.
- The architecture follows arc42-lite chapters (goals, context, strategy, building-blocks, deployment, crosscutting, decisions, risks), the product its own (problem, users, goals, non-goals, features, metrics). Every new section names its chapter.
- A decision is a record: \`adr\` for how it is built, \`pdr\` for what the user gets. It is written to \`docs/decisions/NNNN-*.md\` in MADR 4 form. Link it to the section it shapes (\`records: [id]\`) and update that section.
- A new term, or a term that changes meaning, goes in the glossary, one section per term.
- A task analysis is a mini design doc: one section per chapter (context, goals, design, alternatives, risks).
- Diagrams are Mermaid. Draw the C4 levels as flowcharts with \`[Person]\`, \`[Software system]\` and \`[Container: technology]\` labels. Every \`sequenceDiagram\` gets \`autonumber\` and, right under it, a numbered list explaining each arrow.
- A hand-written document elsewhere starts with front matter \`type:\` (tutorial, how-to, reference or explanation).
`;

/**
 * Writes what a repo is missing from the templates (#133): AGENTS.md and a CLAUDE.md importing
 * it when it has neither, the docs rule when it has none. Never overwrites; a second run writes
 * nothing. Returns the files written.
 * @param {string} root
 */
function writeMissing(root) {
  const s = agentFiles(root);
  const written = [];
  /** @param {string} f @param {string} text */
  const put = (f, text) => {
    if (fs.existsSync(f)) return;
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text, { flag: "wx" });
    written.push(f);
  };
  if (!s.claude && !s.agents) {
    put(s.agentsFile, AGENTS_TEMPLATE);
    put(s.claudeFile, CLAUDE_TEMPLATE);
  } else if (s.agents && !s.claude) put(s.claudeFile, CLAUDE_TEMPLATE);
  if (!s.docsRuleThere) put(s.docsRule, DOCS_RULE);
  return written;
}

/**
 * The checklist's rows for a repo's agent files (#133): files to write from the templates, or
 * a CLAUDE.md to split into AGENTS.md (Fix it).
 * @param {ReturnType<typeof agentFiles>} s
 */
function agentRows(s) {
  /** @type {any[]} */
  const rows = [];
  const missing = [!s.claude && !s.agents && "AGENTS.md and CLAUDE.md", s.agents && !s.claude && "CLAUDE.md", !s.docsRuleThere && ".claude/rules/docs.md"].filter(Boolean);
  if (missing.length)
    rows.push({ type: "leaf", label: `Agent files: write ${missing.join(", ")}`, description: "from Imprimatur's templates", icon: "new-file",
      tooltip: `The repo is missing ${missing.join(" and ")} (#133: AGENTS.md holds the rules every agent follows, CLAUDE.md imports it, .claude/rules/docs.md holds the document rules for docs/**). Click to write them from Imprimatur's templates; nothing is overwritten.`,
      command: "imprimatur.setup.writeAgentFiles" });
  if (s.claude && !s.imports)
    rows.push({ type: "leaf", label: "Agent files: CLAUDE.md does not import AGENTS.md", description: `${s.claudeLines} lines${s.agents ? ", AGENTS.md exists" : ""} · Fix it splits it`, icon: "references",
      tooltip: "AGENTS.md should hold the rules every coding agent follows (up to 200 lines) and CLAUDE.md import it with @AGENTS.md, keeping only what is Claude Code's own (#133). Fix it has Claude propose the split; you see the diffs before anything is written.",
      context: "checkFix", fix: { kind: "agents" } });
  return rows;
}

module.exports = { agentFiles, importsAgents, writeMissing, agentRows, AGENTS_TEMPLATE, CLAUDE_TEMPLATE, DOCS_RULE };
