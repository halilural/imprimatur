// @ts-check
// Design documents as Markdown in the repo (#72): <docs dir>/ARCHITECTURE.md,
// PRODUCT.md and GLOSSARY.md (docs/ unless .claude/imprimatur.json says otherwise, #73), generated
// from the database (the source of truth). docs-sync.js decides when, and takes a
// file's own edits (and a hand-written file, adopted) into the database first.
// A file is written only when its text changed; superseded sections are left out.
// exportDocs alone never overwrites a hand-written file (its first line is not HEADER),
// nor anything outside the repo (the folder or the file a symlink that leads elsewhere).
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const FILES = { architecture: "ARCHITECTURE.md", product: "PRODUCT.md", glossary: "GLOSSARY.md" };
const HEADER = "<!-- Generated by Imprimatur from its database; edit in the Imprimatur panel (Mimari/Ürün). -->";
const KIND_LABEL = { adr: "ADR", pdr: "PDR", decision: "Karar", todo: "Yapılacak", question: "Soru", answer: "Cevap", note: "Not", fixme: "Hata", test: "Test" };

/** One line of Markdown text: no line breaks, no stray link brackets. @param {string} s */
const inline = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

/**
 * A document as Markdown: the header comment, its title, a table of contents and the
 * current sections in order. The contributing records stay in the database and the panel:
 * listed under every section they made the file read like a decision log.
 * @param {any} db @param {number} docId @returns {string | undefined} undefined: no current section
 */
function docMarkdown(db, docId) {
  const doc = db.docById(docId);
  if (!doc) return undefined;
  const sections = db.docSections(docId).filter((/** @type {any} */ s) => s.status === "current");
  if (!sections.length) return undefined;
  // Blocks, a blank line between each. The glossary's terms are not numbered: they read alphabetically.
  const terms = doc.kind === "glossary";
  const out = [HEADER, `# ${inline(doc.title)}`, terms ? "## Terimler" : "## İçindekiler",
    sections.map((/** @type {any} */ s, /** @type {number} */ i) => `${terms ? "-" : `${i + 1}.`} [${inline(s.title).replace(/[[\]]/g, "\\$&")}](#${s.key})`).join("\n")];
  sections.forEach((/** @type {any} */ s, /** @type {number} */ i) => {
    out.push(`<a id="${s.key}"></a>`, terms ? `## ${inline(s.title)}` : `## ${i + 1}. ${inline(s.title)}`);
    const body = String(s.body ?? "").replace(/\r\n/g, "\n").trim();
    if (body) out.push(body);
  });
  return out.join("\n\n") + "\n";
}

/**
 * The repo's folder for the documents (#73): .claude/imprimatur.json {"docs": {"dir": "docs/design"}},
 * relative to the repo; "docs" when unset or not a plain relative path.
 * @param {string} root
 */
function dirOf(root) {
  const dir = docsSettings(root).dir;
  if (typeof dir !== "string" || !dir.trim() || path.isAbsolute(dir) || dir.split(/[\\/]/).includes("..")) return path.join(root, "docs");
  return path.join(root, dir.trim());
}

/** The repo's "docs" settings in .claude/imprimatur.json, {} without. @param {string} root @returns {{dir?: unknown, sync?: unknown}} */
function docsSettings(root) {
  try {
    const docs = JSON.parse(fs.readFileSync(path.join(root, ".claude", "imprimatur.json"), "utf8"))?.docs;
    return docs && typeof docs === "object" ? docs : {};
  } catch {
    return {};
  }
}

/** Whether the documents and their files are synced in this repo: unless {"docs": {"sync": false}}. @param {string} root */
const syncOn = (root) => docsSettings(root).sync !== false;

/** The repo's file for a kind: <root>/<docs dir>/ARCHITECTURE.md, PRODUCT.md or GLOSSARY.md. @param {string} root @param {string} kind */
const fileOf = (root, kind) => path.join(dirOf(root), /** @type {any} */ (FILES)[kind]);

/** Whether the file is there and was not written by Imprimatur (its first line is not HEADER). @param {string} file */
function handWritten(file) {
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch {
    return false;
  }
  return text.split("\n", 1)[0].replace(/\r$/, "") !== HEADER;
}

/** "manual" when the kind's file in the repo is hand-written (the panel says so), else undefined. @param {string} root @param {string} kind */
function fileState(root, kind) {
  return Object.hasOwn(FILES, kind) && handWritten(fileOf(root, kind)) ? "manual" : undefined;
}

/**
 * Whether writing the file stays inside the repo: docs/ (when there) resolves inside the
 * repo's real path, and the file is not a symlink.
 * @param {string} root @param {string} file
 */
function inside(root, file) {
  try {
    const realRoot = fs.realpathSync(root);
    const dir = path.dirname(file);
    if (fs.existsSync(dir)) {
      const rel = path.relative(realRoot, fs.realpathSync(dir));
      if (rel.startsWith("..") || path.isAbsolute(rel)) return false;
    }
    try {
      if (fs.lstatSync(file).isSymbolicLink()) return false;
    } catch {}
    return true;
  } catch {
    return false;
  }
}

/**
 * Writes the repo's documents to <root>/docs/, each only when its text changed.
 * A document with no current section writes nothing (an existing file stays). Skipped:
 * "manual", a hand-written file there; "outside", docs/ or the file leads out of the repo.
 * @param {any} db @param {string} root a repo root on this machine
 * @returns {Array<{kind: string, file: string, written: boolean, skipped?: "manual" | "outside"}>}
 */
function exportDocs(db, root) {
  let repo = db.repoByRoot(root);
  if (!repo) {
    try {
      repo = db.repoByRoot(fs.realpathSync(root));
    } catch {}
  }
  if (!repo) return [];
  const out = [];
  for (const [kind, name] of Object.entries(FILES)) {
    const doc = db.docFind(repo.id, kind);
    const text = doc && docMarkdown(db, doc.id);
    if (!text) continue;
    const file = path.join(dirOf(root), name);
    if (!inside(root, file)) {
      out.push({ kind, file, written: false, skipped: /** @type {const} */ ("outside") });
      continue;
    }
    if (handWritten(file)) {
      out.push({ kind, file, written: false, skipped: /** @type {const} */ ("manual") });
      continue;
    }
    let old;
    try {
      old = fs.readFileSync(file, "utf8");
    } catch {}
    const written = old !== text;
    if (written) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      // Made just now (or raced): checked again.
      if (!inside(root, file)) {
        out.push({ kind, file, written: false, skipped: /** @type {const} */ ("outside") });
        continue;
      }
      // Through a temp file: a reader never sees half of it.
      const tmp = `${file}.${process.pid}.tmp`;
      fs.writeFileSync(tmp, text);
      fs.renameSync(tmp, file);
    }
    out.push({ kind, file, written });
  }
  return out;
}

/**
 * Runs fn once, `ms` after the last of a burst of calls.
 * @param {() => void} fn @param {number} [ms]
 */
function debounce(fn, ms = 2000) {
  /** @type {NodeJS.Timeout | undefined} */
  let timer;
  const call = () => {
    clearTimeout(timer);
    timer = setTimeout(fn, ms);
  };
  call.cancel = () => clearTimeout(timer);
  return call;
}

module.exports = { docMarkdown, exportDocs, debounce, fileState, fileOf, dirOf, docsSettings, syncOn, handWritten, inside, FILES, HEADER };
