// @ts-check
// Design documents as Markdown in the repo (#72): <docs dir>/ARCHITECTURE.md,
// PRODUCT.md and GLOSSARY.md (docs/ unless .claude/imprimatur.json says otherwise, #73), generated
// from the database (the source of truth). docs-sync.js decides when, and takes a
// file's own edits (and a hand-written file, adopted) into the database first.
// A file is written only when its text changed; superseded sections are left out.
// exportDocs alone never overwrites a hand-written file (its first line is not HEADER),
// nor anything outside the repo (the folder or the file a symlink that leads elsewhere).
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const { CHAPTERS, CHAPTER_ANCHOR } = require("./db.js");

const FILES = { architecture: "ARCHITECTURE.md", product: "PRODUCT.md", glossary: "GLOSSARY.md", social: "SOCIAL.md" };
const HEADER = "<!-- Generated by Imprimatur from its database; edit in the Imprimatur panel (Architecture/Product). -->";
/** What every version's header starts with. */
const HEADER_START = "<!-- Generated by Imprimatur from its database";
/**
 * Whether a first line is the header of a generated file, in any version's wording (older ones
 * said "Mimari/Ürün"). Read as hand-written, another version's file would be adopted again and
 * again while both run (2026-10-23: 1131 duplicate sections).
 * @param {string} line
 */
const isHeader = (line) => line.startsWith(HEADER_START) && line.trimEnd().endsWith("-->");

/** Each document's Diátaxis type (#129), in its file's front matter. */
const TYPES = { architecture: "explanation", product: "explanation", glossary: "reference", social: "reference" };
/** The front matter a generated file starts with. @param {string} kind */
const frontMatter = (kind) => `---\ntype: ${/** @type {any} */ (TYPES)[kind] ?? "explanation"}\n---`;

/**
 * Whether Imprimatur wrote a file's text: HEADER on its first line, or on the first line after
 * its front matter (#129: a generated file starts with `type:` front matter, which must come first).
 * @param {string | undefined} text
 */
function generatedText(text) {
  const lines = String(text ?? "").split(/\r?\n/);
  let i = 0;
  if (lines[0]?.trim() === "---") {
    const end = lines.findIndex((l, j) => j > 0 && l.trim() === "---");
    if (end < 0) return false;
    i = end + 1;
    while (i < lines.length && !lines[i].trim()) i++;
  }
  return isHeader(lines[i] ?? "");
}
const KIND_LABEL = { adr: "ADR", pdr: "PDR", decision: "Decision", todo: "To-do", question: "Question", answer: "Answer", note: "Note", fixme: "Fixme", test: "Test" };

/** One line of Markdown text: no line breaks, no stray link brackets. @param {string} s */
const inline = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

/**
 * A document as Markdown: the header comment, its title, a table of contents and the
 * current sections in order. The contributing records stay in the database and the panel:
 * listed under every section they made the file read like a decision log.
 * @param {any} db @param {number} docId @returns {string | undefined} undefined: no current section
 */
function docMarkdown(db, docId) {
  const doc = db.docById(docId);
  if (!doc) return undefined;
  const sections = db.docSections(docId).filter((/** @type {any} */ s) => s.status === "current");
  if (!sections.length) return undefined;
  const chapters = /** @type {Record<string, Record<string, string>>} */ (CHAPTERS)[doc.kind];
  if (chapters) return chaptered(doc, sections, chapters);
  // Blocks, a blank line between each. The glossary's terms are not numbered: they read alphabetically.
  const terms = doc.kind === "glossary";
  const out = [frontMatter(doc.kind), HEADER, `# ${inline(doc.title)}`, terms ? "## Terms" : "## Contents",
    sections.map((/** @type {any} */ s, /** @type {number} */ i) => `${terms ? "-" : `${i + 1}.`} [${link(s.title)}](#${s.key})`).join("\n")];
  sections.forEach((/** @type {any} */ s, /** @type {number} */ i) => {
    out.push(`<a id="${s.key}"></a>`, terms ? `## ${inline(s.title)}` : `## ${i + 1}. ${inline(s.title)}`);
    const body = String(s.body ?? "").replace(/\r\n/g, "\n").trim();
    if (body) out.push(body);
    const decided = require("./decisions.js").linksLine(s.contributors ?? []);
    if (decided) out.push(decided);
  });
  return out.join("\n\n") + "\n";
}

/** A title as link text. @param {string} t */
const link = (t) => inline(t).replace(/[[\]]/g, "\\$&");

/**
 * A document with fixed chapters (#129): every chapter an H2 under `<a id="chapter-…">`, always
 * all of them in order (an empty one says so), its sections H3 numbered through the document;
 * sections with no chapter under "Unsorted" at the end. docSections already sorts by chapter.
 * @param {any} doc @param {any[]} sections @param {Record<string, string>} chapters
 */
function chaptered(doc, sections, chapters) {
  const groups = [...Object.entries(chapters), ["unsorted", "Unsorted"]].map(([id, title]) => ({
    id, title, list: sections.filter((s) => (id === "unsorted" ? !Object.hasOwn(chapters, s.chapter ?? "") : s.chapter === id)),
  })).filter((g) => g.id !== "unsorted" || g.list.length);
  let n = 0;
  const num = new Map(sections.map((s) => [s.key, ++n]));
  const toc = groups.map((g) => [`- [${g.title}](#${CHAPTER_ANCHOR}${g.id})`,
    ...g.list.map((s) => `  ${num.get(s.key)}. [${link(s.title)}](#${s.key})`)].join("\n")).join("\n");
  const out = [frontMatter(doc.kind), HEADER, `# ${inline(doc.title)}`, "## Contents", toc];
  for (const g of groups) {
    out.push(`<a id="${CHAPTER_ANCHOR}${g.id}"></a>`, `## ${g.title}`);
    if (!g.list.length) out.push("_Not written yet._");
    for (const s of g.list) {
      out.push(`<a id="${s.key}"></a>`, `### ${num.get(s.key)}. ${inline(s.title)}`);
      const body = String(s.body ?? "").replace(/\r\n/g, "\n").trim();
      if (body) out.push(body);
      // The decisions it is built on, as links to their MADR files (#130); docs-sync skips the line.
      const decided = require("./decisions.js").linksLine(s.contributors ?? []);
      if (decided) out.push(decided);
    }
  }
  return out.join("\n\n") + "\n";
}

/**
 * The repo's folder for the documents (#73): .claude/imprimatur.json {"docs": {"dir": "docs/design"}},
 * relative to the repo; "docs" when unset or not a plain relative path.
 * @param {string} root
 */
function dirOf(root) {
  const dir = docsSettings(root).dir;
  if (typeof dir !== "string" || !dir.trim() || path.isAbsolute(dir) || dir.split(/[\\/]/).includes("..")) return path.join(root, "docs");
  return path.join(root, dir.trim());
}

/** The repo's "docs" settings in .claude/imprimatur.json, {} without. @param {string} root @returns {{dir?: unknown, sync?: unknown}} */
function docsSettings(root) {
  try {
    const docs = JSON.parse(fs.readFileSync(path.join(root, ".claude", "imprimatur.json"), "utf8"))?.docs;
    return docs && typeof docs === "object" ? docs : {};
  } catch {
    return {};
  }
}

/** Whether the documents and their files are synced in this repo: unless {"docs": {"sync": false}}. @param {string} root */
const syncOn = (root) => docsSettings(root).sync !== false;

/** The repo's .claude/imprimatur.json, {} without or unreadable. @param {string} root @returns {Record<string, unknown>} */
function repoSettings(root) {
  try {
    const all = JSON.parse(fs.readFileSync(path.join(root, ".claude", "imprimatur.json"), "utf8"));
    return all && typeof all === "object" && !Array.isArray(all) ? all : {};
  } catch {
    return {};
  }
}

/** Whether the repo tracks its social media (#109): {"social": true}; off by default. @param {string} root */
const socialOn = (root) => repoSettings(root).social === true;

/**
 * Turns the repo's social media tracking on or off in .claude/imprimatur.json, keeping its other
 * settings. Off keeps the document: turned on again, it is there. @param {string} root @param {boolean} on
 */
function setSocial(root, on) {
  const file = path.join(root, ".claude", "imprimatur.json");
  const all = repoSettings(root);
  if (fs.existsSync(file) && !Object.keys(all).length && fs.readFileSync(file, "utf8").trim()) throw new Error(`Imprimatur: ${file} is not valid JSON; fix it first`);
  if (on) all.social = true;
  else delete all.social;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(all, null, 2)}\n`);
}

/** The document kinds the repo keeps in files: social only when it is on. @param {string} root */
const kindsOf = (root) => Object.keys(FILES).filter((k) => k !== "social" || socialOn(root));

/** The repo's file for a kind: <root>/<docs dir>/ARCHITECTURE.md, PRODUCT.md or GLOSSARY.md. @param {string} root @param {string} kind */
const fileOf = (root, kind) => path.join(dirOf(root), /** @type {any} */ (FILES)[kind]);

/** Whether the file is there and was not written by Imprimatur (no HEADER, after any front matter). @param {string} file */
function handWritten(file) {
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch {
    return false;
  }
  return !generatedText(text);
}

/** "manual" when the kind's file in the repo is hand-written (the panel says so), else undefined. @param {string} root @param {string} kind */
function fileState(root, kind) {
  return Object.hasOwn(FILES, kind) && handWritten(fileOf(root, kind)) ? "manual" : undefined;
}

/**
 * Whether writing the file stays inside the repo: docs/ (when there) resolves inside the
 * repo's real path, and the file is not a symlink.
 * @param {string} root @param {string} file
 */
function inside(root, file) {
  try {
    const realRoot = fs.realpathSync(root);
    const dir = path.dirname(file);
    if (fs.existsSync(dir)) {
      const rel = path.relative(realRoot, fs.realpathSync(dir));
      if (rel.startsWith("..") || path.isAbsolute(rel)) return false;
    }
    try {
      if (fs.lstatSync(file).isSymbolicLink()) return false;
    } catch {}
    return true;
  } catch {
    return false;
  }
}

/**
 * Writes the repo's documents to <root>/docs/, each only when its text changed.
 * A document with no current section writes nothing (an existing file stays). Skipped:
 * "manual", a hand-written file there; "outside", docs/ or the file leads out of the repo.
 * @param {any} db @param {string} root a repo root on this machine
 * @returns {Array<{kind: string, file: string, written: boolean, skipped?: "manual" | "outside"}>}
 */
function exportDocs(db, root) {
  let repo = db.repoByRoot(root);
  if (!repo) {
    try {
      repo = db.repoByRoot(fs.realpathSync(root));
    } catch {}
  }
  if (!repo) return [];
  const out = [];
  // Decisions get their MADR numbers first (#130), so the documents' links name them on this export.
  const decides = kindsOf(root).some((k) => k === "architecture" || k === "product");
  if (decides)
    try {
      require("./decisions.js").numbered(db, repo.id);
    } catch {}
  for (const kind of kindsOf(root)) {
    const name = /** @type {any} */ (FILES)[kind];
    const doc = db.docFind(repo.id, kind);
    const text = doc && docMarkdown(db, doc.id);
    if (!text) continue;
    const file = path.join(dirOf(root), name);
    if (!inside(root, file)) {
      out.push({ kind, file, written: false, skipped: /** @type {const} */ ("outside") });
      continue;
    }
    if (handWritten(file)) {
      out.push({ kind, file, written: false, skipped: /** @type {const} */ ("manual") });
      continue;
    }
    let old;
    try {
      old = fs.readFileSync(file, "utf8");
    } catch {}
    const written = old !== text;
    if (written) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      // Made just now (or raced): checked again.
      if (!inside(root, file)) {
        out.push({ kind, file, written: false, skipped: /** @type {const} */ ("outside") });
        continue;
      }
      // Through a temp file: a reader never sees half of it.
      const tmp = `${file}.${process.pid}.tmp`;
      fs.writeFileSync(tmp, text);
      fs.renameSync(tmp, file);
    }
    out.push({ kind, file, written });
  }
  // The decisions as MADR 4 files beside the documents (#130), when the repo keeps architecture or product in files.
  // Side files: written, not listed (the list is the documents').
  if (decides)
    try {
      require("./decisions.js").exportDecisions(db, repo, dirOf(root), { header: `${HEADER_START}; edit the decision's record in Imprimatur (its task, Tasks tab). -->`, generatedText, inside: (f) => inside(root, f) });
    } catch {}
  return out;
}

/**
 * Runs fn once, `ms` after the last of a burst of calls.
 * @param {() => void} fn @param {number} [ms]
 */
function debounce(fn, ms = 2000) {
  /** @type {NodeJS.Timeout | undefined} */
  let timer;
  const call = () => {
    clearTimeout(timer);
    timer = setTimeout(fn, ms);
  };
  call.cancel = () => clearTimeout(timer);
  return call;
}

module.exports = { docMarkdown, exportDocs, debounce, fileState, fileOf, dirOf, docsSettings, syncOn, repoSettings, socialOn, setSocial, kindsOf, handWritten, inside, FILES, HEADER, isHeader, generatedText, TYPES };
